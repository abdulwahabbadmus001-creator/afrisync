CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT UNIQUE NOT NULL,
    username TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    created_at TEXT DEFAULT CURRENT_TIMESTAMP,
    email TEXT,
    full_name TEXT,
    email_verified INTEGER DEFAULT 1,
    email_verified_at TEXT,
    is_disabled INTEGER DEFAULT 0,
    disabled_at TEXT,
    disabled_reason TEXT,
    updated_at TEXT,
    password_updated_at TEXT,
    google_sub TEXT,
    auth_provider TEXT DEFAULT 'password',
    google_linked_at TEXT,
    avatar_url TEXT
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email_unique
ON users (lower(email))
WHERE email IS NOT NULL AND email != '';

CREATE UNIQUE INDEX IF NOT EXISTS idx_users_google_sub_unique
ON users (google_sub)
WHERE google_sub IS NOT NULL AND google_sub != '';

CREATE TABLE IF NOT EXISTS projects (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    location TEXT,
    progress INTEGER DEFAULT 0,
    sync_status TEXT DEFAULT 'SYNCED',
    project_uuid TEXT UNIQUE,
    user_id TEXT,
    is_deleted INTEGER DEFAULT 0,
    deleted_at TEXT,
    version INTEGER DEFAULT 1,
    updated_at TEXT,
    conflict_data TEXT
);

CREATE TABLE IF NOT EXISTS password_reset_tokens (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash TEXT UNIQUE NOT NULL,
    user_id TEXT NOT NULL,
    username TEXT NOT NULL,
    created_at TEXT NOT NULL,
    expires_at TEXT NOT NULL,
    used_at TEXT
);

CREATE INDEX IF NOT EXISTS idx_password_reset_user
ON password_reset_tokens (user_id, used_at, expires_at);

CREATE INDEX IF NOT EXISTS idx_password_reset_hash
ON password_reset_tokens (token_hash);

CREATE TABLE IF NOT EXISTS email_verification_codes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_hash TEXT NOT NULL,
    user_id TEXT NOT NULL,
    email TEXT NOT NULL,
    created_at TEXT NOT NULL,
    expires_at TEXT NOT NULL,
    used_at TEXT,
    attempts INTEGER DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_email_verification_user
ON email_verification_codes (user_id, used_at, expires_at);

CREATE INDEX IF NOT EXISTS idx_email_verification_code
ON email_verification_codes (code_hash);

CREATE TABLE IF NOT EXISTS project_notes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    note_uuid TEXT UNIQUE NOT NULL,
    project_uuid TEXT NOT NULL,
    user_id TEXT NOT NULL,
    content TEXT NOT NULL,
    sync_status TEXT DEFAULT 'SYNCED',
    is_deleted INTEGER DEFAULT 0,
    deleted_at TEXT,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    version INTEGER DEFAULT 1,
    conflict_data TEXT
);

CREATE INDEX IF NOT EXISTS idx_server_notes_user_updated
ON project_notes (user_id, updated_at);

CREATE INDEX IF NOT EXISTS idx_server_notes_project
ON project_notes (project_uuid, user_id, is_deleted);

CREATE TABLE IF NOT EXISTS project_attachments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attachment_uuid TEXT UNIQUE NOT NULL,
    project_uuid TEXT NOT NULL,
    user_id TEXT NOT NULL,
    original_file_name TEXT NOT NULL,
    stored_file_name TEXT NOT NULL,
    file_path TEXT NOT NULL,
    file_type TEXT DEFAULT 'application/octet-stream',
    file_size INTEGER DEFAULT 0,
    sync_status TEXT DEFAULT 'SYNCED',
    is_deleted INTEGER DEFAULT 0,
    deleted_at TEXT,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    version INTEGER DEFAULT 1,
    conflict_data TEXT
);

CREATE INDEX IF NOT EXISTS idx_server_attachments_user_updated
ON project_attachments (user_id, updated_at);

CREATE INDEX IF NOT EXISTS idx_server_attachments_project
ON project_attachments (project_uuid, user_id, is_deleted);

CREATE INDEX IF NOT EXISTS idx_server_attachments_uuid_user
ON project_attachments (attachment_uuid, user_id);

CREATE TABLE IF NOT EXISTS project_members (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_uuid TEXT NOT NULL,
    owner_user_id TEXT NOT NULL,
    member_user_id TEXT NOT NULL,
    member_username TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'VIEWER',
    is_deleted INTEGER DEFAULT 0,
    invited_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    UNIQUE(project_uuid, member_user_id)
);

CREATE INDEX IF NOT EXISTS idx_project_members_member
ON project_members (member_user_id, is_deleted);

CREATE INDEX IF NOT EXISTS idx_project_members_project
ON project_members (project_uuid, is_deleted);

CREATE TABLE IF NOT EXISTS admin_sessions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_token TEXT UNIQUE NOT NULL,
    created_at TEXT NOT NULL,
    expires_at TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_admin_sessions_token
ON admin_sessions (session_token, expires_at);

CREATE TABLE IF NOT EXISTS admin_action_logs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action_uuid TEXT UNIQUE NOT NULL,
    action_type TEXT NOT NULL,
    target_type TEXT NOT NULL,
    target_id TEXT,
    details TEXT,
    created_at TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_admin_action_logs_created
ON admin_action_logs (created_at);
CREATE INDEX IF NOT EXISTS idx_admin_action_logs_target
ON admin_action_logs (target_type, target_id);
